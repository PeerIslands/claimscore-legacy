CREATE TABLE CLAIMS (
    CLAIM_ID               NUMBER(12)      NOT NULL,
    CLAIM_NUM              VARCHAR2(20)    NOT NULL,
    PH_ID                  NUMBER(12)      NOT NULL,
    PLAN_ID                NUMBER(12)      NOT NULL,
    PROVIDER_ID            NUMBER(12)      NOT NULL,
    CLAIM_TYPE_CD          VARCHAR2(4)     NOT NULL,
    STATUS_CD              VARCHAR2(4)     NOT NULL,
    POS_CD                 CHAR(2),
    INCIDENT_DT            DATE            NOT NULL,
    RECEIVED_DT            DATE            DEFAULT SYSDATE NOT NULL,
    ADJUDICATED_DT         DATE,
    TOTAL_BILLED_AMT       NUMBER(12,2)    DEFAULT 0 NOT NULL,
    TOTAL_ALLOWED_AMT      NUMBER(12,2)    DEFAULT 0,
    TOTAL_PAID_AMT         NUMBER(12,2)    DEFAULT 0,
    PATIENT_LIAB_AMT       NUMBER(12,2)    DEFAULT 0,
    DEDUCTIBLE_APPLIED_AMT NUMBER(12,2)    DEFAULT 0,
    DENIAL_REASON_CD       VARCHAR2(6),
    VERSION_NO             NUMBER(6)       DEFAULT 0 NOT NULL,
    CREATED_BY             VARCHAR2(30),
    CREATED_DT             DATE            DEFAULT SYSDATE,
    UPDATED_BY             VARCHAR2(30),
    UPDATED_DT             DATE,
    CONSTRAINT PK_CLAIMS PRIMARY KEY (CLAIM_ID),
    CONSTRAINT UK_CLAIMS_CLAIM_NUM UNIQUE (CLAIM_NUM)
);
COMMENT ON TABLE CLAIMS IS 'Claim header. One row per submitted claim; totals are maintained by PKG_CLAIMS.ADJUDICATE_CLAIM.';
CREATE INDEX IX_CLAIMS_PH ON CLAIMS (PH_ID);
CREATE INDEX IX_CLAIMS_STATUS ON CLAIMS (STATUS_CD);
CREATE INDEX IX_CLAIMS_PROVIDER_DT ON CLAIMS (PROVIDER_ID, INCIDENT_DT);

